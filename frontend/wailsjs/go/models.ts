	export class ImageGenConfig {
	    provider: string;
	    downloadPath: string;
	    openrouter: OpenRouterImageConfig;
	    openai: OpenAIImageConfig;
	    google: GoogleImageConfig;
	    xai: XAIImageConfig;
	
	    static createFrom(source: any = {}) {
	        return new ImageGenConfig(source);
	    }
	
	    constructor(source: any = {}) {
	        if ('string' === typeof source) source = JSON.parse(source);
	        this.provider = source["provider"];
	        this.downloadPath = source["downloadPath"];
	        this.openrouter = this.convertValues(source["openrouter"], OpenRouterImageConfig);
	        this.openai = this.convertValues(source["openai"], OpenAIImageConfig);
	        this.google = this.convertValues(source["google"], GoogleImageConfig);
	        this.xai = this.convertValues(source["xai"], XAIImageConfig);
	    }
	
		convertValues(a: any, classs: any, asMap: boolean = false): any {
		    if (!a) {
		        return a;
		    }
		    if (a.slice && a.map) {
		        return (a as any[]).map(elem => this.convertValues(elem, classs));
		    } else if ("object" === typeof a) {
		        if (asMap) {
		            for (const key of Object.keys(a)) {
		                a[key] = new classs(a[key]);
		            }
		            return a;
		        }
		        return new classs(a);
		    }
		    return a;
		}
	}
